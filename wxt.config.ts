import { $ } from "bun"
import { defineConfig } from "wxt"

import { buildVersion } from "./scripts/release-version"

export default defineConfig({
	srcDir: "src",
	manifestVersion: 3,
	zip: {
		artifactTemplate: "{{name}}-{{version}}-{{browser}}{{modeSuffix}}.zip",
		sourcesTemplate: "{{name}}-{{version}}-sources{{modeSuffix}}.zip",
		includeSources: [
			"src/**",
			"scripts/**",
			"public/**",
			"vendor/**",
			"docs/**",
			"voice-previews/texts.json",
			"voice-previews/README.md",
			"package.json",
			"bun.lock",
			"bunfig.toml",
			"tsconfig*.json",
			"wxt.config.ts",
			"README.md",
			"SOURCE_CODE_REVIEW.md",
			"LICENSE",
			"NOTICE.md",
		],
		excludeSources: ["public/runtime/**", "public/pdf-runtime/**", "voice-previews/*.wav"],
	},
	hooks: {
		"prepare:publicPaths": (_, paths) => {
			// These entrypoints are generated by build:before, after WXT prepares
			// asset types on a clean checkout. Declare their exact paths up front.
			for (const path of ["runtime/cpu/speech.js", "runtime/gpu/speech.js", "runtime/instrument.js"])
				if (!paths.includes(path)) paths.push(path)
		},
		"build:before": async () => {
			await $`bun scripts/prepare-runtime.ts`.quiet()
		},
	},
	manifest: ({ browser }) => ({
		name: "Read Aloud",
		version: buildVersion(),
		icons: {
			16: "icons/icon-16.png",
			32: "icons/icon-32.png",
			48: "icons/icon-48.png",
			96: "icons/icon-96.png",
			128: "icons/icon-128.png",
		},
		description: "Read pages and selected text aloud on your device.",
		permissions: [
			"activeTab",
			"scripting",
			"contextMenus",
			"storage",
			// Voice models can be large and must remain available offline.
			"unlimitedStorage",
			...(browser === "chrome" ? ["offscreen" as const] : []),
		],
		...(browser === "chrome"
			? {
					// Voice downloads and PCM transport use the typed-array encoding APIs
					// introduced in Chrome 140.
					minimum_chrome_version: "140",
					cross_origin_embedder_policy: { value: "require-corp" as const },
					cross_origin_opener_policy: { value: "same-origin" as const },
				}
			: {}),
		optional_host_permissions: ["https://*/*", "http://*/*", "file:///*"],
		action: { default_title: "Read this page" },
		options_ui: { page: "voices.html", open_in_tab: true },
		web_accessible_resources: [{ resources: ["player.html"], matches: ["<all_urls>"] }],
		content_security_policy: {
			extension_pages:
				"script-src 'self' 'wasm-unsafe-eval'; object-src 'none'; worker-src 'self'; connect-src 'self' http: https: file:",
		},
		...(browser === "firefox"
			? {
					browser_specific_settings: {
						gecko: {
							id: process.env.FIREFOX_EXTENSION_ID || "read-aloud@fidasek009.github.io",
							strict_min_version: "140.0",
							data_collection_permissions: { required: ["none"] },
						},
					},
				}
			: {}),
	}),
})
